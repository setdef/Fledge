# Writes doc/licensing.md, the page that tells developers who build apps
# with Fledge what ships inside each app and what each license asks of
# them, from the license audit of each platform's runtime (ADR 004).
#
# The maintainer asked for this page to come from the pipeline, never by
# hand (decisions.md, replies of 2026-10-26), so it holds only what the
# audit finds in the runtimes, and prose that names license sections.
# CI builds the four runtimes, runs this with --check, and fails when the
# page in the repository differs from what the runtimes say.
#
#   ruby tasks/licensing_page.rb RUNTIMES_DIR          # write doc/licensing.md
#   ruby tasks/licensing_page.rb --check RUNTIMES_DIR  # exit 1 if it is stale
#
# RUNTIMES_DIR holds one fledge-runtime-VERSION-PLATFORM.tar.gz for each
# platform; their contents, not their version, decide the page (a
# runtime's files do not change with Fledge's version), and the page names
# Fledge::VERSION.
class LicensingPage
  PAGE = File.join(LicenseAudit::ROOT, "doc", "licensing.md")
  RELEASES = "https://github.com/setdef/Fledge/releases"

  # What a person sees for each platform.
  TITLES = {
    "arm64-darwin" => "macOS on Apple Silicon (arm64-darwin)",
    "x86_64-linux" => "Linux on x86-64 (x86_64-linux)",
    "aarch64-linux" => "Linux on ARM64 (aarch64-linux)",
    "x64-mingw-ucrt" => "Windows on x64 (x64-mingw-ucrt)",
  }.freeze

  # The Ruby every runtime is made from, for the page's prose.
  RUBY_VERSION_SHIPPED = YAML.safe_load_file(LicenseAudit::SOURCES).fetch("ruby").fetch("version")

  # What the page needs of a platform's Report, read before its tree is
  # deleted: its components but gems, its gems' names by license, and
  # its LGPL libraries.
  class Summary < Data.define(:components, :gems, :lgpl); end

  # A component, as the page shows it.
  class Row < Data.define(:name, :version, :license, :ships, :files); end

  def initialize(runtimes, version: Fledge::VERSION)
    @runtimes = runtimes
    @version = version
  end

  # The page, from the audit of each platform's runtime.
  def text
    reports = Fledge::Platform.names.to_h { |platform| [platform, audit(platform)] }
    [header, everywhere(reports), app_gems, *reports.map { |platform, report| section(platform, report) }, lgpl(reports), footer].join("\n")
  end

  # Audits the runtime archive for +platform+ in the runtimes folder.
  def audit(platform)
    archives = Dir.glob(File.join(@runtimes, "fledge-runtime-*-#{platform}.tar.gz"))
    raise "#{@runtimes} holds no single runtime for #{platform}: #{archives}" unless archives.size == 1

    Dir.mktmpdir("licensing-#{platform}") do |directory|
      Fledge::Archive.unpack(archives.first.to_s, into: directory)
      tree = Dir.glob(File.join(directory, "fledge-runtime-*")).first or raise "#{archives.first} holds no runtime folder"
      report = LicenseAudit.new(platform:, tree:, fledge_version: @version).call
      raise "the #{platform} runtime breaks the license policy: #{report.violations.first}" unless report.violations.empty?

      summarize(report)
    end
  end

  private def summarize(report)
    present = report.present
    rows = present.reject(&:gem_dir).sort_by { |component| [component.first_party ? 0 : 1, component.name.downcase] }.map do |component|
      Row.new(name: component.name, version: component.version, license: component.license, ships: component.ships,
        files: report.owned(component))
    end
    gems = present.select(&:gem_dir).group_by(&:license).transform_values { |list| list.map { |gem| gem.name[/\A\S+/] }.sort }
    lgpl = rows.select { |row| row.license.include?("LGPL") }
    Summary.new(components: rows, gems: gems.sort.to_h, lgpl:)
  end

  private def header
    <<~HEADER
      <!--
        SPDX-FileCopyrightText: 2026 Kerrick Long <me@kerricklong.com>
        SPDX-License-Identifier: CC-BY-SA-4.0
      -->

      <!-- Generated by tasks/licensing_page.rb from the license audit of each runtime. Do not edit; CI fails when it is stale. -->

      # What Ships Inside an App Built with Fledge, and What Its Licenses Ask of You

      This page lists, for Fledge #{@version}, every third-party component of the runtime that `fledge build` copies into an app on each platform, the license it is under, and what that license asks of you when you give the app to other people. Your app's own gems are yours, not Fledge's, and [their section](#your-apps-own-gems) says what Fledge does with them. Fledge's CI writes it from the same license audit that every runtime must pass before it is published (ADR 004), so it lists what the runtimes hold, not what someone remembered.

      It states facts and cites the sections of each license they come from. It is not legal advice, and it makes no claim about what any license requires of you in your situation: ask your own lawyer.

      Each app carries the same facts in `notices/NOTICES.txt` (every component, its license, and the full text of every license) and `notices/sbom.spdx.json` (an SPDX 2.3 software bill of materials listing every file with its checksums and what each compiled file links). Each [release](#{RELEASES}) publishes both for every platform, beside the runtime they describe, as `fledge-runtime-VERSION-PLATFORM-NOTICES.txt` and `fledge-runtime-VERSION-PLATFORM.spdx.json`.
    HEADER
  end

  private def everywhere(reports)
    ours = reports.fetch("x86_64-linux").components.find { |row| row.license == "AGPL-3.0-or-later" } or raise "no runtime holds Fledge's own files"
    <<~EVERYWHERE
      ## On every platform

      **Your own code stays yours.** Nothing in a runtime asks for your app's source code or object files. The GPL appears in a runtime only with an exception that lifts its terms from programs compiled with the code (GCC's runtime library exception, LLVM's exception, Bison's exception) or beside a permissive license you may take instead (Perl's Artistic License, for Ruby's `win32/win32.c`); the LGPL appears only as a separate shared library, or linked into a program that is not Fledge's own and whose source Fledge publishes with the library's (AppImage's runtime, in a Linux app's AppImage). Fledge's license policy (`runtime/licenses.yml`) fails the build of any runtime that holds anything else, including an LGPL library linked into Fledge's launcher, the program your app's users run.

      **Keep the notices.** The permissive licenses below ask that copies of the software keep their copyright notices and license texts: MIT asks that "the above copyright notice and this permission notice shall be included in all copies or substantial portions of the Software"; BSD-2-Clause and BSD-3-Clause ask that a redistribution in binary form "reproduce the above copyright notice, this list of conditions and the following disclaimer in the documentation and/or other materials provided with the distribution"; Apache-2.0, section 4, asks for a copy of the license and the attribution notices; Ruby is under Ruby's license or, at your choice, BSD-2-Clause. Fledge puts all of them in the app's `notices/NOTICES.txt`; ship the app's folder with its `notices/` folder in it.

      **The CA certificates** (`cert.pem`) are under the Mozilla Public License 2.0, whose obligations attach to the file itself. It ships unmodified, in its source form, which MPL-2.0, section 3.1, asks be distributed under the MPL with word of how to get a copy of it; `notices/NOTICES.txt` holds that copy, and the file's own notices stay intact (section 3.4).

      **A windowed app's installers** (ADR 009) hold the app, its `notices/` with them, and on Windows and Linux more of the runtime's components, which its section lists as shipping in `tools/`: a Windows app's setup program is made of NSIS's stub and plug-ins (the zlib license, which asks nothing of a binary) and compressed with NSIS's LZMA module, which is under the Common Public License 1.0: its section 3 asks that a program distributed in object code say that its source is available and how to get it, and Fledge does both, publishing NSIS's source in `fledge-runtime-VERSION-x64-mingw-ucrt-lgpl-sources.tar.gz` beside each Windows runtime and saying so in the app's `notices/NOTICES.txt`, which the setup program installs; and a Linux app's AppImage begins with AppImage's runtime (MIT), as AppImage releases it, with libfuse (LGPL-2.1, as [below](#libraries-under-the-lgpl) says), squashfuse (BSD-2-Clause), zstd (BSD-3-Clause), zlib, mimalloc, and musl (MIT) linked in. A macOS app's disk image holds nothing but the app. Each installer's notices are the app's `notices/NOTICES.txt`, which it holds.

      **Fledge's own files** in an app are #{ours.files.map { |file| "`#{file}`" }.join(' and ')} (the first is the program your app's users run, renamed for your app). They are Fledge's work, under the GNU Affero General Public License, version 3 or later. If you give an app to others, the AGPL asks you to convey the Corresponding Source of those files under its terms (AGPL-3.0, section 6): Fledge's own source at the tag of the version that built the app, which `notices/NOTICES.txt` names. Fledge's maintainer has said that a commercial license will likely be offered (through [setdef](https://setdef.com)) for apps that don't want to follow the AGPL; none is offered yet.
    EVERYWHERE
  end

  # What the page says of an app's own gems: that they, and their
  # licenses, are the developer's (the maintainer's words of 2026-10-28;
  # ADR 007), and where their own notices are in the app.
  private def app_gems
    <<~GEMS
      ## Your app's own gems

      Fledge takes no position on the licenses of the gems your app depends on. Which gems your app uses, and what their licenses ask of you, are your choice and your responsibility, as they are however else you ship a Ruby app. `fledge build` ships every gem your `Gemfile.lock` locks for each platform (leaving out its `development` and `test` groups), whatever its license, whether or not it declares one, and whatever its compiled files hold. Everything else on this page, the policy and the obligations alike, is about what Fledge itself puts into your app: its runtime.

      Each gem ships as RubyGems or Bundler installs it, with all of its own files, its license files among them, in the app's gem folder (`lib/ruby/gems/4.0.0/` on macOS and Linux, `ruby\\lib\\ruby\\gems\\4.0.0\\` on Windows), and its specification, which declares its license, in that folder's `specifications/`. Fledge writes no notices of its own for your gems: `bundle licenses` lists the license each one's specification declares, and each gem's own notices say what it asks of you. `fledge build` refuses a gem only when it would not run where the app goes: one with an extension that does not compile, one whose `required_ruby_version` excludes Ruby #{RUBY_VERSION_SHIPPED}, or one whose compiled files need a library that neither the operating system, nor the runtime, nor the gem itself provides.
    GEMS
  end

  private def section(platform, summary)
    rows = summary.components.map do |row|
      "| #{cell(row.name)} | #{cell(row.version)} | `#{cell(row.license)}` | #{cell(row.ships)} |"
    end
    gems = summary.gems.map { |license, names| "- `#{cell(license)}`: #{names.join(', ')}" }
    obligations = summary.lgpl.empty? ? "Nothing beyond the notices and Fledge's own files above: no LGPL library ships on this platform." : obligation(platform, summary.lgpl)
    <<~SECTION
      ## #{TITLES.fetch(platform)}

      | Component | Version | License | How it ships |
      |---|---|---|---|
      #{rows.join("\n")}

      Its #{summary.gems.values.sum(&:size)} default and bundled gems, the ones every Ruby #{RUBY_VERSION_SHIPPED} installs, by the license each one's specification declares (or `runtime/licenses.yml` corrects):

      #{gems.join("\n")}

      **What you must do on this platform:** #{obligations}
    SECTION
  end

  private def obligation(platform, rows)
    libraries = rows.map do |row|
      where = row.files.empty? ? "linked into AppImage's runtime" : row.files.map { |file| "`#{file}`" }.join(", ")
      "#{row.name.sub(/,.*/, '')} (#{where})"
    end
    "keep the notices and Fledge's own files as above, and meet the LGPL for #{libraries.join(' and for ')}, as " \
      "[below](#libraries-under-the-lgpl) says. The source is `#{LicenseAudit::Notices.source_bundle(@version, platform)}` in Fledge's release."
  end

  private def lgpl(_reports)
    <<~LGPL
      ## Libraries under the LGPL

      Three libraries are under the GNU Lesser General Public License: libxcrypt, in Linux apps, as `lib/libcrypt.so.2`, and GNU MP (GMP), in Windows apps, as `ruby\\bin\\ruby_builtin_dlls\\libgmp-10.dll`, each its own shared library, which the app loads when it starts, and which CI proves on every push can be replaced with another build (`ci.yml`, Replace libcrypt and Replace GMP); and libfuse, linked into AppImage's runtime, the program at the front of a Linux app's AppImage, which mounts the app's files and starts the app, never into the app itself. The LGPL asks nothing of your app's own source or object files used either way. It does ask the following of whoever gives the app to others. Fledge does the parts marked as Fledge's; the rest are yours.

      ### libxcrypt (LGPL-2.1-or-later)

      - A prominent notice that the library is used in the app and that it and its use are covered by the LGPL, and a copy of the license (LGPL-2.1, section 6). Fledge's `notices/NOTICES.txt` does this.
      - If your app displays copyright notices while it runs, include the library's among them, with a reference to the license (section 6).
      - Use a suitable shared library mechanism, so that a modified, interface-compatible version the user installs works (section 6(b)). Fledge's layout does this: leave `lib/libcrypt.so.2` a separate file.
      - Make the library's source available, in one of the ways section 6 lists: accompany the app with it (6(a)), offer access to it from the same place you offer the app (6(d)), or include a written offer, valid for at least three years, to give it (6(c)). Fledge publishes the exact source, and how its copy was built, as the release asset `fledge-runtime-VERSION-PLATFORM-lgpl-sources.tar.gz`, and keeps every release, and so every bundle, published. You may also ship that bundle beside your app's download yourself, which section 6(a) and 6(d) describe most directly. Because the license is "or later", you may instead take LGPL-3.0's terms, which convey source by GNU GPL version 3, section 6; its section 6(d) allows the source to be "on a different server (operated by you or a third party)" with "clear directions next to the object code", while you "remain obligated to ensure that it is available for as long as needed".
      - Your app's terms must permit modification of the work for the customer's own use and reverse engineering for debugging such modifications (section 6, first paragraph). This falls on your license agreement, if your app has one.

      ### libfuse (LGPL-2.1-only), in a Linux app's AppImage

      libfuse is linked into AppImage's runtime (MIT), a program of its own that is not your app and not Fledge's launcher; the app inside the AppImage is started by it, and links nothing of libfuse. The LGPL's terms for a work linked with the library apply to that runtime, and Fledge meets the ones that ask for source:

      - A prominent notice that the library is used and is covered by the LGPL, and a copy of the license (LGPL-2.1, section 6). Fledge's `notices/NOTICES.txt`, which the AppImage holds, does this, and so does the runtime's own `--appimage-help`.
      - The complete machine-readable source of the library, and of the runtime it is linked into, so that whoever receives the AppImage can modify libfuse and relink the runtime with it (section 6(a)). Fledge publishes both, AppImage's runtime at the commit it was built from, with its build scripts and its patch to libfuse, and libfuse's release, in `fledge-runtime-VERSION-PLATFORM-lgpl-sources.tar.gz` beside each Linux runtime, and keeps every release published. You may ship that bundle beside your AppImage yourself, as section 6(a) describes most directly.
      - Terms that permit modification of the runtime for the customer's own use and reverse engineering for debugging such modifications (section 6, first paragraph) concern the runtime, which is MIT and permits both; your app's own terms need say nothing of it.

      ### GNU MP (LGPL-3.0-or-later OR GPL-2.0-or-later)

      GMP offers a choice of licenses; under the LGPL-3.0 option:

      - A prominent notice that the library is used and is covered by the LGPL (LGPL-3.0, section 4(a)), and copies of the GNU GPL and the LGPL (4(b)). Fledge's `notices/NOTICES.txt` does this.
      - If your app displays copyright notices while it runs, include the library's, with a reference to those licenses (4(c)).
      - Use a suitable shared library mechanism (4(d)(1)). Fledge's layout does this: leave `libgmp-10.dll` a separate file in `ruby\\bin\\ruby_builtin_dlls\\`.
      - Convey the library's Corresponding Source as GNU GPL version 3, section 6 describes, as for libxcrypt above. Fledge's Windows release asset holds MSYS2's source package of the very build RubyInstaller ships, which CI checks byte for byte.
      - Installation Information (4(e)) is needed only where GPL-3.0, section 6, would require it, which is when the app is conveyed in, with, or specifically for use in a "User Product", such as a consumer device it comes installed on.
      - Your app's terms must not restrict modification of the library's portions and reverse engineering for debugging such modifications (section 4, first paragraph).

      Some companies' open-source policies forbid LGPL-3.0 components; if yours does, GMP in Windows apps is the one to raise.
    LGPL
  end

  private def footer
    <<~FOOTER
      ## Where this comes from

      `runtime/licenses.yml` holds the policy and the map of what is compiled into what; `tasks/license_audit.rb` checks each runtime against it as the runtime is built; this page and each runtime's `notices/` come from that audit. Questions about Fledge's own licensing go to the maintainer, through [the repository](https://github.com/setdef/Fledge).
    FOOTER
  end

  private def cell(text)
    text.to_s.gsub("|", "\\|").gsub("\n", " ")
  end
end

if $PROGRAM_NAME == __FILE__
  check = ARGV.delete("--check")
  runtimes = ARGV.first or abort "usage: licensing_page.rb [--check] RUNTIMES_DIR"
  text = LicensingPage.new(runtimes).text
  if check
    current = File.exist?(LicensingPage::PAGE) ? File.read(LicensingPage::PAGE) : ""
    if current == text
      puts "doc/licensing.md matches the runtimes"
    else
      File.write(File.join(runtimes, "licensing.md"), text)
      abort "doc/licensing.md is stale: run ruby tasks/licensing_page.rb on these runtimes and commit it " \
        "(the expected page is #{File.join(runtimes, 'licensing.md')})"
    end
  else
    File.write(LicensingPage::PAGE, text)
    puts "Wrote #{LicensingPage::PAGE}"
  end
end
