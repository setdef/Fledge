require "digest"

# Writes lib/fledge/linkage/windows.yml, the DLLs every Windows a Fledge
# app runs on has in System32, which Fledge::Linkage lets a gem's
# compiled files need, from delvewheel's own lists
# (doc/contributors/design/gems.md, "What Windows provides").
#
# delvewheel, which repairs Python's Windows wheels as auditwheel repairs
# Linux's, keeps in delvewheel/_dll_list.py the lowercase name of every
# DLL found in System32 on the installation discs of each x64 Windows
# from 7 SP1 to 11 (ignore_names_x64), and of each ARM64 Windows from 10
# to 11 (ignore_names_arm64). This reads that file, at the commit and
# SHA-256 below, so an update arrives on purpose: change the pins, then
#
#   ruby tasks/windows_dlls.rb PATH_TO/_dll_list.py
#
# where the file is https://raw.githubusercontent.com/adang1345/delvewheel/COMMIT/delvewheel/_dll_list.py.
module WindowsDlls
  # delvewheel's commit, whose delvewheel/_version.py says 1.13.2.
  COMMIT = "0cf6869e9791f3b2f43a3a3e61123bb160f4b969"

  # The SHA-256 of delvewheel/_dll_list.py at COMMIT.
  SHA256 = "9022e4bab1eaae4bf9137a8cf9a64d56ba8081bc9c4a995c4782fef57239f01d"

  # Each list Fledge reads, by Fledge::Platform#libraries.
  SETS = { "windows" => "ignore_names_x64", "windows-arm64" => "ignore_names_arm64" }.freeze

  # Where the list goes.
  OUTPUT = File.expand_path("../lib/fledge/linkage/windows.yml", __dir__)

  # The names in the Python set literal +name+ in +source+.
  def self.names(source, name)
    body = source[/^#{name} = \{\n(.*?)^\}/m, 1] or raise "delvewheel's _dll_list.py has no #{name}"
    body.scan(/^\s*'([^']+)',?\s*$/).flatten.sort
  end

  # The YAML file Fledge reads, with its header, from +source+.
  def self.document(source)
    header = <<~YAML
      # Generated by tasks/windows_dlls.rb from delvewheel's
      # delvewheel/_dll_list.py at #{COMMIT}. Do not edit:
      # change the generator's pins and run it again.
      #
      # SPDX-FileCopyrightText: 2026 setdef <kerrick@setdef.com>
      # SPDX-License-Identifier: MIT
      #
      # SPDX-SnippetBegin
      # SPDX-SnippetCopyrightText: 2020 Aohan Dang
      # SPDX-License-Identifier: MIT
      # SPDX-SnippetComment: ignore_names_x64 and ignore_names_arm64 of delvewheel/_dll_list.py, delvewheel at #{COMMIT}
    YAML
    lists = SETS.map { |key, name| "#{key}:\n#{names(source, name).map { |dll| "  - #{dll}\n" }.join}" }
    "#{header}#{lists.join}# SPDX-SnippetEnd\n"
  end

  # Writes OUTPUT from the file at +path+, which must be the pinned one.
  def self.write(path)
    source = File.binread(path)
    actual = Digest::SHA256.hexdigest(source)
    raise "#{path} has SHA-256 #{actual}, not delvewheel #{COMMIT}'s #{SHA256}" unless actual == SHA256

    File.write(OUTPUT, document(source.force_encoding(Encoding::UTF_8)))
  end
end

WindowsDlls.write(ARGV.fetch(0) { abort "usage: ruby tasks/windows_dlls.rb PATH_TO/_dll_list.py" }) if $PROGRAM_NAME == __FILE__
