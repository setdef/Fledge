require_relative "test_helper"
require_relative "../tasks/windows_dlls"

# tasks/windows_dlls.rb, which writes lib/fledge/linkage/windows.yml
# from delvewheel's lists of the DLLs every Windows has.
class WindowsDllsTest < Minitest::Test
  SOURCE = <<~PYTHON
    ignore_names_x86 = {
        'only32.dll',
    }

    ignore_names_x64 = {
        'kernel32.dll',
        'd2d1.dll',
    }

    ignore_names_arm64 = {
        'xinputuap.dll',
    }
  PYTHON

  def test_it_reads_each_architectures_set_sorted
    assert_equal %w[d2d1.dll kernel32.dll], WindowsDlls.names(SOURCE, "ignore_names_x64")
    assert_equal %w[xinputuap.dll], WindowsDlls.names(SOURCE, "ignore_names_arm64")
  end

  def test_a_file_without_the_set_is_refused
    error = assert_raises(RuntimeError) { WindowsDlls.names("ignore_names_x86 = {\n}\n", "ignore_names_x64") }
    assert_includes error.message, "no ignore_names_x64"
  end

  def test_the_document_is_yaml_keyed_by_what_linkage_reads
    lists = YAML.safe_load(WindowsDlls.document(SOURCE))
    assert_equal({ "windows" => %w[d2d1.dll kernel32.dll], "windows-arm64" => %w[xinputuap.dll] }, lists)
  end

  def test_only_the_pinned_file_is_read
    Dir.mktmpdir do |dir|
      path = File.join(dir, "_dll_list.py")
      File.write(path, SOURCE)
      error = assert_raises(RuntimeError) { WindowsDlls.write(path) }
      assert_includes error.message, WindowsDlls::SHA256
    end
  end

  # The checked-in list is the generator's, from the pinned commit.
  def test_the_list_in_lib_names_the_pinned_commit
    header = File.read(WindowsDlls::OUTPUT).lines.take_while { |line| line.start_with?("#") }.join
    assert_includes header, "Generated by tasks/windows_dlls.rb"
    assert_includes header, WindowsDlls::COMMIT
    assert_equal WindowsDlls::SETS.keys, Fledge::Linkage::SYSTEM_DLLS.keys
  end
end
