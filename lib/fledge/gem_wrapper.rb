module Fledge
  # RubyGems' wrapper for one command of one gem: the file
  # <tt>gem install</tt> and <tt>bundle install</tt> write in Ruby's bin
  # folder, which activates the gem and loads the command's script from
  # its folder, so that the person who types the command's name runs it.
  #
  # A desktop build has its runtime's RubyGems write the wrapper
  # (Fledge::NativeBuild#binstubs). An Android build has no Ruby to run
  # that RubyGems: the phone's cannot run where the project is written,
  # and the desktop runtime of the computer that writes it is one more
  # download, and one CI's computers that write a phone's project do not
  # have. So this writes the text the phone's RubyGems writes, at the
  # Ruby the runtimes carry, for a wrapper written as Fledge has its
  # runtime's RubyGems write one: with <tt>/usr/bin/env ruby</tt> for
  # Ruby's path, which a relocatable Ruby cannot know, and no
  # <tt>custom_shebang</tt> of anyone's <tt>.gemrc</tt>.
  # test/gem_wrapper_test.rb holds it to the text RubyGems itself writes.
  #
  # [gem] The gem's name.
  # [program] The command's name, a file in the gem's bin folder.
  # [script] That file's contents, whose <tt>#!</tt> line's options the
  #          wrapper keeps.
  #
  # === Example
  #
  #--
  # SPDX-SnippetBegin
  # SPDX-SnippetCopyrightText: 2026 setdef <kerrick@setdef.com>
  # SPDX-License-Identifier: MIT-0
  #++
  #   Fledge::GemWrapper.new(gem: "rake", program: "rake", script: "#!/usr/bin/env ruby\n").text.lines.first # => "#!/bin/sh\n"
  #--
  # SPDX-SnippetEnd
  #++
  class GemWrapper < Data.define(:gem, :program, :script)
    # What <tt>Gem.ruby</tt> is as Fledge's runtimes write a wrapper: the
    # Ruby first on +PATH+, which is the app's own.
    RUBY = "/usr/bin/env ruby"

    # The phone's rbconfig.rb's +ruby_install_name+.
    RUBY_INSTALL_NAME = "ruby"

    #--
    # SPDX-SnippetBegin
    # SPDX-License-Identifier: Ruby OR MIT
    # SPDX-SnippetCopyrightText: Chad Fowler, Rich Kilmer, Jim Weirich and others
    # SPDX-SnippetComment: Gem::Installer#app_script_text, #gemdeps_load,
    #   #explicit_version_requirement, #shebang, and #bash_prolog_script,
    #   adapted from RubyGems' lib/rubygems/installer.rb at Ruby
    #   v4.1.0-preview1 (2d08b5f42f), lines 746 to 800, 588 to 622, and
    #   1039 to 1056, for a gem's script given as text, Gem.ruby as RUBY,
    #   no custom_shebang or env_shebang, the default prerelease
    #   requirement as its text, and a Ruby built with
    #   --enable-load-relative, as every runtime of Fledge's is.
    #++

    # The wrapper's text.
    def text
      # NOTE: that the `load` lines cannot be indented, as old RG versions match
      # against the beginning of the line
      escaped_bin_file_name = program.gsub(/[\\']/) { |c| "\\#{c}" }
      <<~TEXT
        #{shebang}
        #
        # This file was generated by RubyGems.
        #
        # The application '#{gem}' is installed as part of a gem, and
        # this file is here to facilitate running it.
        #

        require 'rubygems'
        #{gemdeps_load}
        version = ">= 0.a"

        str = ARGV.first
        if str
          str = str.b[/\\A_(.*)_\\z/, 1]
          if str and Gem::Version.correct?(str)
            #{explicit_version_requirement}
            ARGV.shift
          end
        end

        if Gem.respond_to?(:activate_and_load_bin_path)
          Gem.activate_and_load_bin_path('#{gem}', '#{escaped_bin_file_name}', version)
        else
          load Gem.activate_bin_path('#{gem}', '#{escaped_bin_file_name}', version)
        end
      TEXT
    end

    private def gemdeps_load
      return "" if gem == "bundler"

      <<~TEXT

        Gem.use_gemdeps
      TEXT
    end

    private def explicit_version_requirement
      code = "version = str"
      return code unless gem == "bundler"

      code += <<~TEXT

        ENV['BUNDLER_VERSION'] = str
      TEXT
    end

    # The <tt>#!</tt> lines, which keep the extra words on the script's
    # own, like <tt>-w</tt>.
    private def shebang
      first_line = script.b.lines.first || ""
      opts = first_line[/\A\#!.*?ruby\S*((\s+\S+)+)/, 1] if first_line.start_with?("#!")
      "#{bash_prolog_script}#!#{RUBY}#{opts}"
    end

    private def bash_prolog_script
      <<~EOS
        #!/bin/sh
        # -*- ruby -*-
        _=_\\
        =begin
        bindir="${0%/*}"
        ruby="$bindir/#{RUBY_INSTALL_NAME}"
        if [ ! -f "$ruby" ]; then
          ruby="#{RUBY_INSTALL_NAME}"
        fi
        exec "$ruby" "-x" "$0" "$@"
        =end
      EOS
    end

    #--
    # SPDX-SnippetEnd
    #++
  end
end
